// Drives real Chrome against `wrangler dev`: save, refresh, submit gate, second submission log.
import puppeteer from "puppeteer-core";
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const gap = (...a) => execFileSync("node", ["bin/gap.mjs", ...a], { encoding: "utf8" });
const created = JSON.parse(gap("new", "--name", "Test", "--title", "E2E case"));
const qf = "/tmp/gap-q-" + process.pid + ".json";
writeFileSync(qf, JSON.stringify([{ title: "A", note: "n", first: true, questions: [{ id: "a1", text: "One?", why: "w" }, { id: "a2", text: "Two?" }] }]));
gap("publish", created.id, "--questions", qf, "--status", "open");
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new" });
const page = await browser.newPage();
const ok = (c, m) => { if (!c) throw new Error("FAILED: " + m); console.log("ok  " + m); };
const dis = (id) => page.$eval(id, (e) => e.disabled);
const txt = (id) => page.$eval(id, (e) => e.textContent);
const settle = (id) => page.waitForFunction((i) => !document.querySelector(i).disabled, {}, id);
await page.goto(created.link, { waitUntil: "networkidle0" });
await page.waitForSelector("#q-a1");
ok((await page.$$(".saverow button")).length === 0, "no per-question save buttons");
ok(await dis("#saveAll"), "save disabled before any change");
await page.type("#q-a1", "first answer");
ok(!(await dis("#saveAll")), "save activates on change");
ok(await dis("#submit"), "submit blocked while unsaved");
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#q-a1");
ok((await page.$eval("#q-a1", (e) => e.value)) === "first answer", "unsaved draft survives refresh");
ok(!(await dis("#saveAll")), "restored draft still needs saving");
await page.click("#saveAll");
await page.waitForFunction(() => document.querySelector("#saveAll").textContent === "All changes saved");
await settle("#submit");
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#q-a1");
ok((await page.$eval("#q-a1", (e) => e.value)) === "first answer", "saved answer comes from the server after refresh");
await page.click("#submit");
await page.waitForFunction(() => /Submission 1 received/.test(document.querySelector("#submitStatus").textContent));
ok(true, "submission 1 received");
await page.type("#q-a2", "second answer");
ok(await dis("#submit"), "submit blocks again after an edit");
await page.click("#saveAll");
await page.waitForFunction(() => document.querySelector("#saveAll").textContent === "All changes saved");
await settle("#submit"); await page.click("#submit");
await page.waitForFunction(() => /Submission 2 received/.test(document.querySelector("#submitStatus").textContent));
ok((await txt("#submitStatus")).includes("Q2"), "submission 2 names what changed");
const s2 = JSON.parse(gap("fetch", created.id)), s1 = JSON.parse(gap("fetch", created.id, "--seq", "1"));
ok(s2.seq === 2 && s2.intact && s2.items[1].answer === "second answer", "latest log is intact and complete");
ok(s1.seq === 1 && s1.intact && s1.items[1].answer === "", "first log is unchanged");
const other = JSON.parse(gap("new", "--name", "Other", "--title", "Other goal"));
gap("publish", other.id, "--questions", qf, "--status", "open"); gap("cost", other.id, "0.25", "research");
await page.goto(created.link + "#group", { waitUntil: "networkidle0" });
await page.waitForFunction(() => /Other/.test(document.querySelector("#people").textContent));
ok((await txt("#people")).includes("$0.250"), "group shows each person's cost");
await page.goto(created.link + "#view-" + other.id, { waitUntil: "networkidle0" });
await page.waitForFunction(() => /read only/.test(document.querySelector("#eyebrow").textContent));
ok((await page.$$eval("#viewList li", (l) => l.length)) === 2 && (await page.$eval("#qBox", (e) => e.hidden)), "another page opens read only");
const api = (path, init) => fetch(other.link + "/api" + path, init);
const leak = await (await api("/view/" + created.id)).text();
ok(!leak.includes("first answer") && !leak.includes("second answer"), "other people's answers are never returned");
await fetch(created.link + "/api/visibility", { method: "PUT", body: JSON.stringify({ visible: false }) });
ok((await api("/view/" + created.id)).status === 403, "a hidden page is refused");
const list = await (await api("/group")).json();
const row = list.people.find((p) => p.id === created.id);
ok(row && !row.visible && list.people[0].id !== other.id, "hidden page stays listed, oldest first");
gap("purge", other.id);
await browser.close();
const bad = await fetch(new URL(created.link).origin + "/c/wrongtoken"); ok(bad.status === 404, "wrong link is refused");
const adm = await fetch(new URL(created.link).origin + "/admin/cases"); ok(adm.status === 404, "admin needs its token");
gap("purge", created.id); console.log("ALL PASSED");
