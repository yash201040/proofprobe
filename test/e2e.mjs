// Drives real Chrome against `wrangler dev` on localhost only.
import puppeteer from "puppeteer-core";
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync } from "node:fs";
const config = ".proofprobe/test-config.json";
const base = "http://localhost:8799";
const main = JSON.parse(readFileSync(".proofprobe/config.json", "utf8"));
writeFileSync(config, JSON.stringify({ adminToken: main.adminToken, baseUrl: base, passwords: {} }));
const env = { ...process.env, GAP_CONFIG: config };
const pp = (...a) => execFileSync("node", ["bin/proofprobe.mjs", ...a], { encoding: "utf8", env });
const ppFails = (...a) => { try { execFileSync("node", ["bin/proofprobe.mjs", ...a], { stdio: "ignore", env }); return false; } catch { return true; } };
const ok = (c, m) => { if (!c) throw new Error("FAILED: " + m); console.log("ok  " + m); };
const qf = "/tmp/proofprobe-q-" + process.pid + ".json";
writeFileSync(qf, JSON.stringify([{ title: "A", note: "n", first: true, questions: [{ id: "a1", text: "One?", why: "w" }, { id: "a2", text: "Two?", catchAll: true }] }]));
const made = (profile, title) => { const c = JSON.parse(pp("new", "--profile", profile, "--title", title)); pp("publish", c.id, "--questions", qf, "--status", "open"); return { ...c, api: c.link.replace("/probes/", "/api/pages/") }; };
const setPw = (c) => (c.pw = pp("password", c.id).match(/password: (\S+)/)[1]);
const first = made("Test Person", "First goal"), second = made("Test Person", "Second goal"), other = made("Other Person", "Other goal");
setPw(first); second.pw = first.pw; setPw(other);
const cleanup = [first.id, second.id, other.id];
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new" });
try {
const page = await browser.newPage();
const dis = (id) => page.$eval(id, (e) => e.disabled);
const txt = (id) => page.$eval(id, (e) => e.textContent);
const shown = (id) => page.$eval(id, (e) => !e.hidden);
const saved = () => page.waitForFunction(() => document.querySelector("#saveAll").textContent === "All changes saved");
const settle = (id) => page.waitForFunction((i) => !document.querySelector(i).disabled, {}, id);
const unlock = async (pw) => { await page.click("#unlockBtn"); await page.type("#password", pw); await page.click("#unlockGo"); };

await page.goto(base + "/", { waitUntil: "networkidle0" });
ok((await txt("h1")).includes("One proven path"), "home page loads");
await page.click("#burger"); ok((await page.$eval("#menu a", (e) => e.getAttribute("href"))) === "/probes" && (await page.$$("#menu a svg")).length === 3, "menu links to Probes with icons");
await page.goto(base + "/probes", { waitUntil: "networkidle0" });
await page.waitForSelector(".profile");
const cards = await page.$$eval(".profile", (l) => l.map((c) => [c.querySelector("h2").textContent, c.querySelectorAll(".pagelink").length]));
ok(cards.some(([n, c]) => n === "Test Person" && c === 2), "one profile can hold several pages");

const paint = await browser.newPage();
await paint.setRequestInterception(true);
paint.on("request", (r) => { if (r.url().includes("/api/pages/")) setTimeout(() => r.continue(), 900); else r.continue(); });
await paint.goto(first.link, { waitUntil: "domcontentloaded" });
ok((await paint.$("#loadbar")) && (await paint.$("#skel")), "the loading bar shows before content arrives");
await paint.waitForSelector("#access:not([hidden])"); await paint.waitForFunction(() => !document.querySelector("#loadbar"));
ok(!(await paint.$("#skel")), "the loading bar clears when content arrives"); await paint.close();
await page.goto(first.link, { waitUntil: "networkidle0" }); await page.waitForSelector("#access:not([hidden])");
ok((await shown("#viewQs")) && !(await shown("#qBox")) && (await page.$$("#form textarea")).length === 0, "a visitor gets a read-only page");
const anon = await fetch(first.api + "/answers", { method: "PUT", body: JSON.stringify({ answers: { a1: "hack" } }) });
const anonSub = await fetch(first.api + "/submit", { method: "POST", body: JSON.stringify({ key: "anon-key-001" }) });
ok(anon.status === 401 && anonSub.status === 401, "writing without a password is refused");
await unlock("wrong-password-1");
await page.waitForFunction(() => /isn't right/.test(document.querySelector("#unlockErr").textContent));
ok(!(await shown("#qBox")), "a wrong password does not unlock");
await page.$eval("#password", (e) => (e.value = ""));
await page.click("#unlockGo").catch(() => {});
await page.type("#password", first.pw); await page.click("#unlockGo");
await page.waitForSelector("#q-a1"); ok(await shown("#qBox"), "the right password unlocks editing");

ok(await dis("#saveAll"), "save disabled before any change");
await page.type("#q-a1", "first answer");
ok(!(await dis("#saveAll")), "save activates on change");
ok(await dis("#submit"), "submit blocked while unsaved");
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#q-a1");
ok((await page.$eval("#q-a1", (e) => e.value)) === "first answer", "unlock and draft survive a refresh");
await page.click("#saveAll"); await saved(); await settle("#submit");
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#q-a1");
ok((await page.$eval("#q-a1", (e) => e.value)) === "first answer", "saved answer comes from the server");
await page.click("#submit");
await page.waitForFunction(() => /Submission 1 received/.test(document.querySelector("#submitStatus").textContent));
await page.type("#q-a2", "second answer"); ok(await dis("#submit"), "submit blocks again after an edit");
await page.click("#saveAll"); await saved(); await settle("#submit"); await page.click("#submit");
await page.waitForFunction(() => /Submission 2 received/.test(document.querySelector("#submitStatus").textContent));
const s2 = JSON.parse(pp("fetch", first.id)), s1 = JSON.parse(pp("fetch", first.id, "--seq", "1"));
ok(s2.seq === 2 && s2.intact && s2.items[1].answer === "second answer" && s1.items[1].answer === "", "submission logs are complete and separate");

const cookies = await page.cookies(); const c = cookies.find((x) => x.name.startsWith("pp_edit_"));
ok(c && c.httpOnly && c.sameSite === "Strict", "the unlock cookie is protected");
const cross = await fetch(other.api + "/answers", { method: "PUT", headers: { Cookie: `${c.name}=${c.value}` }, body: JSON.stringify({ answers: { a1: "x" } }) });
const sibling = await fetch(second.api + "/answers", { method: "PUT", headers: { Cookie: `${c.name}=${c.value}` }, body: JSON.stringify({ answers: { a1: "x" } }) });
ok(sibling.status === 200, "one password unlocks every page in that profile");
ok(cross.status === 401, "it never unlocks another person's profile");

await page.type("#q-a1", " draft"); await page.click("#saveAll"); await saved();
const pub = await (await fetch(first.api)).json();
ok(pub.seq === 2 && pub.items[1].answer === "second answer" && !JSON.stringify(pub).includes("first answer draft") && !pub.answers, "visitors see submitted answers, not saved edits");
const stale = await page.evaluate(async (api) => (await fetch(api + "/answers", { method: "PUT", body: JSON.stringify({ answers: { a1: "old" }, bases: { a1: "2000-01-01" } }) })).status, first.api.replace(base, ""));
ok(stale === 409, "a stale save is refused");

const noRe = await fetch(first.api + "/reroute", { method: "POST", body: JSON.stringify({ message: "x" }) });
ok(noRe.status === 401 && (await dis("#rerouteSend")), "changing direction needs the password and a message");
await page.type("#rerouteText", "Focus on product roles instead");
await page.click("#rerouteSend");
await page.waitForFunction(() => /Received/.test(document.querySelector("#rerouteState").textContent));
const rerouted = await (await fetch(first.api)).json();
ok(rerouted.reroute?.message === "Focus on product roles instead" && JSON.parse(pp("status", first.id)).reroute, "a new direction is stored and starts nothing");
const dir = await (await fetch(base + "/api/probes")).json();
ok(dir.profiles.flatMap((p) => p.pages).some((g) => g.rerouting), "the directory shows the change of direction");
pp("publish", first.id, "--questions", qf);
ok((await (await fetch(first.api)).json()).reroute === null, "publishing new questions closes the request");
writeFileSync(qf + ".intro", JSON.stringify([{ t: "section", title: "Compare", blocks: [{ t: "table", head: ["Route", "Fit"], rows: [["A", { text: "High", tone: "good" }], ["B", { text: "7/10", score: 7 }]] }, { t: "bars", title: "Fit", max: 10, items: [{ label: "A", value: 8 }] }] }]));
pp("publish", first.id, "--intro", qf + ".intro");
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#intro .fold");
ok((await page.$("#intro .chip.good")) && (await page.$("#intro .meter .fill")) && (await page.$("#intro .barrow .fill")), "folding sections, grades, meters and bars render");
writeFileSync(qf + ".bad", JSON.stringify([{ t: "ul", items: "oops" }]));
ok(ppFails("publish", first.id, "--intro", qf + ".bad"), "a malformed block is refused");
writeFileSync(qf + ".less", JSON.stringify([{ title: "A", questions: [{ id: "a9", text: "New?", catchAll: true }] }]));
ok(ppFails("publish", first.id, "--questions", qf + ".less"), "publishing can't drop earlier questions");
ok((await txt(".notice")).startsWith("Privacy:"), "privacy notice is shown");

const newPw = pp("password", first.id).match(/password: (\S+)/)[1];
await page.reload({ waitUntil: "networkidle0" }); await page.waitForSelector("#access:not([hidden])");
ok(!(await shown("#qBox")) && newPw !== first.pw, "changing a password locks open devices");
const tries = []; for (let i = 0; i < 12; i++) tries.push((await fetch(other.api + "/unlock", { method: "POST", body: JSON.stringify({ password: "guess-" + i }) })).status);
ok(tries.every((s) => s === 401), "wrong guesses never lock anyone out");
const right = await fetch(other.api + "/unlock", { method: "POST", body: JSON.stringify({ password: other.pw }) });
ok(right.status === 200, "the right password still works after many wrong ones");
ok(!ppFails("password", other.id, "--set", "shortpw") , "a short custom password can be set");
// Admin area
ok((await page.goto(base + "/admin", { waitUntil: "networkidle0" })).ok(), "admin page loads");
ok((await fetch(base + "/api/admin/overview")).status === 401, "admin data needs a login");
ok((await fetch(base + "/api/admin/pages/" + first.id + "/password")).status === 401, "passwords need a login");
ok((await fetch(base + "/api/admin/setup", { method: "POST", body: JSON.stringify({ code: "wrong", password: "long-enough-pw" }) })).status === 403, "setup needs a valid code");
const setup = pp("admin-setup").match(/https?:\S+/)[0];
await page.goto("about:blank"); await page.goto(setup, { waitUntil: "networkidle0" });
await page.waitForSelector("#setup:not([hidden])");
await page.type("#newMaster", "test-master-pass"); await page.type("#newMaster2", "test-master-pass");
await page.click("#setup button");
await page.waitForSelector("#login:not([hidden])");
ok((await fetch(base + "/api/admin/setup", { method: "POST", body: JSON.stringify({ code: setup.split("setup=")[1], password: "another-long-pw" }) })).status === 403, "a setup link works only once");
await page.type("#master", "wrong-password"); await page.click("#login button");
await page.waitForFunction(() => /isn't right/.test(document.querySelector("#loginErr").textContent));
await page.$eval("#master", (e) => (e.value = "")); await page.type("#master", "test-master-pass"); await page.click("#login button");
await page.waitForSelector("#rows tr");
ok((await page.$$("#tiles .tile")).length === 4 && (await txt("#rows")).includes("First goal"), "the dashboard lists every page");
const row = `[...document.querySelectorAll("#profiles tr")].find((r) => r.textContent.includes("Test Person"))`;
await page.evaluate((r) => { const i = eval(r).querySelector(".pwi"); i.value = "chosen-by-admin"; eval(r).querySelector(".pwset").click(); }, row);
await page.waitForFunction(() => /Saved for/.test(document.querySelector("#pwMsg").textContent));
await page.waitForFunction((r) => eval(r)?.querySelector(".show"), {}, row);
await page.evaluate((r) => eval(r).querySelector(".show").click(), row);
await page.waitForFunction(() => document.querySelector("#profiles").textContent.includes("chosen-by-admin"));
ok(true, "admin can set and reveal a profile password");
await page.type("#newProfile", "Fresh Profile"); await page.click("#addProfile");
await page.waitForFunction(() => document.querySelector("#profiles").textContent.includes("Fresh Profile"));
ok(true, "admin can add a profile before it has pages");
await page.evaluate(() => [...document.querySelectorAll("#rows tr")].find((r) => r.textContent.includes("First goal")).querySelector("td:nth-child(8) button").click());
await page.waitForSelector("#a-a2");
ok((await fetch(first.api + "/unlock", { method: "POST", body: JSON.stringify({ password: "chosen-by-admin" }) })).status === 200, "the admin's password opens the profile");
await page.$eval("#a-a2", (e) => { e.value = "edited by admin"; }); await page.click("#saveAnswers");
await page.waitForFunction(() => /Saved/.test(document.querySelector("#saveMsg").textContent) || document.querySelector("#a-a2").value === "edited by admin");
const seen2 = JSON.parse(pp("status", first.id));
ok(seen2.savedAnswers === 2, "admin can edit anyone's answers");
const logged = await page.evaluate(async (id) => (await (await fetch("/api/admin/pages/" + id)).json()).audit.map((a) => a.action), first.id);
ok(logged.includes("answers_edited") && logged.includes("password_viewed"), "admin actions are logged");
const bad = []; for (let i = 0; i < 6; i++) bad.push((await fetch(base + "/api/admin/login", { method: "POST", body: JSON.stringify({ password: "guess" + i }) })).status);
ok(bad[5] === 429, "repeated master password guesses are paused");
ok((await fetch(base + "/api/admin/login", { method: "POST", body: JSON.stringify({ password: "test-master-pass" }) })).status === 429, "the pause also applies to the right password");
ok((await fetch(base + "/probes/none/none/x")).status === 404, "unknown paths are refused");
ok((await fetch(base + "/admin/cases")).status === 404, "admin needs its token");
console.log("ALL PASSED");
} finally { await browser.close(); for (const id of cleanup) pp("purge", id); }
